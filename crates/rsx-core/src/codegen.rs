//! Generates Rust from a parsed `.rsx` file.
//!
//! Each component produces four items:
//!
//! * a writer function (`card`) holding the actual rendering code,
//! * a struct (`Card`) holding the parameters,
//! * an `impl Template for Card` that defers to the function,
//! * a constructor function (`Card`) for positional calls.
//!
//! The function is the primitive and the struct is what makes components
//! composable. Calls from markup go through the struct so that a plain
//! `use path::to::Card;` is all an importing file needs — the snake_case
//! function never has to be in scope.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::ast::{self, *};
use crate::error::{Error, Result};
use crate::naming::{to_snake_case, SYNTH_LIFETIME_PREFIX};
use crate::registry::{Registry, Scope};
use crate::source_map::SourceMap;
use crate::span::Pos;

/// Code generation settings.
#[derive(Debug, Clone)]
pub struct Options {
    /// Path to the runtime crate, as written in generated code.
    pub runtime: String,
    /// Whether to emit the "do not edit" banner.
    pub header: bool,
}

impl Default for Options {
    fn default() -> Self {
        Options {
            runtime: "::rsx".to_string(),
            header: true,
        }
    }
}

/// Generates Rust source for a parsed file.
pub fn generate(file: &File, registry: &Registry, options: &Options) -> Result<String> {
    generate_with_map(file, registry, options).map(|(code, _)| code)
}

/// Generates Rust source along with the map from its lines back to the `.rsx`.
pub fn generate_with_map(
    file: &File,
    registry: &Registry,
    options: &Options,
) -> Result<(String, SourceMap)> {
    generate_in(file, &registry.scope(&[], file), options)
}

/// Generates a file that sits at `module_path` within a larger compilation.
pub fn generate_at(
    module_path: &[String],
    file: &File,
    registry: &Registry,
    options: &Options,
) -> Result<(String, SourceMap)> {
    generate_in(file, &registry.scope(module_path, file), options)
}

fn generate_in(file: &File, scope: &Scope<'_>, options: &Options) -> Result<(String, SourceMap)> {
    let mut gen = Generator {
        out: String::new(),
        depth: 0,
        rt: options.runtime.clone(),
        scope,
        statics: String::new(),
        statics_origin: None,
        children_params: Vec::new(),
        map: SourceMap::new(),
        generated_line: 0,
        position: None,
    };

    if options.header {
        gen.line("// Code generated by rsx. DO NOT EDIT.");
        gen.line("#![allow(clippy::all)]");
        gen.blank();
    }

    for item in &file.items {
        match item {
            Item::Rust(rust) => {
                // Whitespace between items is re-created by `separate`, so
                // passing the original through as well would stack blank lines.
                if !rust.source.trim().is_empty() {
                    gen.separate();
                    let text = format!("{}\n", rust.source.trim());
                    gen.emit(&text);
                }
            }
            Item::Component(component) => {
                gen.separate();
                let pos = component.span.from;
                gen.at(pos, |gen| gen.component(component))?;
            }
        }
    }

    if !gen.out.ends_with('\n') {
        gen.out.push('\n');
    }
    Ok((gen.out, gen.map))
}

struct Generator<'a, 'r> {
    out: String,
    depth: usize,
    rt: String,
    scope: &'a Scope<'r>,
    /// Pending static HTML, batched into one `raw` call.
    statics: String,
    /// Where the pending run of static HTML began. A run can span several
    /// nodes, and it belongs to the first of them rather than to whichever
    /// node happened to force the flush.
    statics_origin: Option<Pos>,
    /// Parameters of the component being generated that carry markup.
    children_params: Vec<String>,
    map: SourceMap,
    /// Lines written so far. Every line leaves through `emit`, so counting
    /// there keeps the map exact.
    generated_line: u32,
    /// The node currently being generated, if any.
    position: Option<Pos>,
}

/// A piece of a generated line: literal text, or Rust copied from the
/// template and therefore worth mapping.
struct Part<'a> {
    text: std::borrow::Cow<'a, str>,
    source: Option<crate::span::Span>,
}

impl<'a> Part<'a> {
    fn lit(text: &'a str) -> Self {
        Part {
            text: std::borrow::Cow::Borrowed(text),
            source: None,
        }
    }

    fn owned(text: String) -> Self {
        Part {
            text: std::borrow::Cow::Owned(text),
            source: None,
        }
    }

    /// A fragment copied straight from the template.
    fn frag(rust: &'a ast::Rust) -> Self {
        Part {
            text: std::borrow::Cow::Borrowed(&rust.text),
            source: Some(rust.span),
        }
    }

    /// Owned text that nonetheless came from `span` in the template.
    fn mapped(text: String, span: crate::span::Span) -> Self {
        Part {
            text: std::borrow::Cow::Owned(text),
            source: Some(span),
        }
    }
}

/// A component parameter resolved for code generation.
struct ResolvedParam {
    name: String,
    /// Whether the writer function binds this parameter `mut`.
    mutable: bool,
    /// Where the type was written, so hovering it can reach `rust-analyzer`.
    /// `None` for a children parameter, whose type is invented here.
    ty_span: Option<crate::span::Span>,
    /// The type as it appears in the generated function.
    fn_ty: String,
    /// The type as it appears in the generated struct, with named lifetimes.
    struct_ty: String,
    is_children: bool,
}

impl Generator<'_, '_> {
    // ---------------------------------------------------------------- emit

    /// Appends text, keeping the line count and the source map in step.
    fn emit(&mut self, text: &str) {
        if let Some(pos) = self.position {
            self.map.record(self.generated_line + 1, pos);
        }
        self.out.push_str(text);
        self.generated_line += text.matches('\n').count() as u32;
    }

    fn line(&mut self, s: &str) {
        self.line_parts(&[Part::lit(s)]);
    }

    /// Emits a line built from literal text and Rust fragments, recording
    /// where each fragment landed.
    ///
    /// The mapping has to be byte-exact rather than line-level: answering
    /// "what can follow this dot" means asking `rust-analyzer` about the same
    /// character of the generated code, not the same line.
    fn line_parts(&mut self, parts: &[Part<'_>]) {
        let mut buffer = String::with_capacity(self.depth * 4 + 1);
        for _ in 0..self.depth {
            buffer.push_str("    ");
        }

        // Where this line will start once `emit` appends it.
        let line_start = self.out.len();
        let mut offsets = Vec::new();
        for part in parts {
            if let Some(span) = part.source {
                offsets.push((line_start + buffer.len(), span, part.text.len()));
            }
            buffer.push_str(&part.text);
        }
        buffer.push('\n');

        self.emit(&buffer);
        for (generated, span, len) in offsets {
            self.map.record_fragment(generated, span, len);
        }
    }

    fn blank(&mut self) {
        self.emit("\n");
    }

    /// Ensures exactly one blank line before the next item.
    fn separate(&mut self) {
        if self.out.is_empty() {
            return;
        }
        while self.out.ends_with('\n') {
            self.out.pop();
            self.generated_line -= 1;
        }
        self.out.push_str("\n\n");
        self.generated_line += 2;
    }

    /// Runs `body` with `pos` as the position every emitted line maps to.
    fn at<T>(&mut self, pos: Pos, body: impl FnOnce(&mut Self) -> T) -> T {
        let saved = self.position.replace(pos);
        let result = body(self);
        self.position = saved;
        result
    }

    fn open(&mut self, s: &str) {
        self.line(s);
        self.depth += 1;
    }

    fn open_parts(&mut self, parts: &[Part<'_>]) {
        self.line_parts(parts);
        self.depth += 1;
    }

    fn close(&mut self, s: &str) {
        self.depth = self.depth.saturating_sub(1);
        self.line(s);
    }

    /// Queues static HTML for the next `raw` call.
    fn push_static(&mut self, s: &str) {
        if self.statics_origin.is_none() {
            self.statics_origin = self.position;
        }
        self.statics.push_str(s);
    }

    /// Emits everything queued by `push_static` as one call.
    fn flush_statics(&mut self) {
        if self.statics.is_empty() {
            self.statics_origin = None;
            return;
        }
        let batched = std::mem::take(&mut self.statics);
        let origin = self.statics_origin.take();
        let literal = rust_string_literal(&batched);

        let saved = self.position;
        if origin.is_some() {
            self.position = origin;
        }
        self.line(&format!("__w.raw({literal})?;"));
        self.position = saved;
    }

    // ----------------------------------------------------------- component

    fn component(&mut self, c: &Component) -> Result<()> {
        if !c
            .name
            .chars()
            .next()
            .is_some_and(|ch| ch.is_ascii_uppercase())
        {
            return Err(Error::new(
                format!("component `{}` must start with an uppercase letter", c.name),
                c.name_span,
            )
            .with_help(
                "markup tells components from HTML elements by their case, so `<Card />` is a \
                 component and `<card />` is an element",
            ));
        }

        let prim = to_snake_case(&c.name);
        let (params, synth_lifetimes) = self.resolve_params(c)?;
        self.children_params = params
            .iter()
            .filter(|p| p.is_children)
            .map(|p| p.name.clone())
            .collect();

        let generics = Generics::build(&c.generics, &synth_lifetimes, &params, &self.rt);
        let where_clause = if c.where_clause.is_empty() {
            String::new()
        } else {
            format!(" where {}", c.where_clause)
        };

        if !c.attrs.trim().is_empty() {
            for line in c.attrs.trim().lines() {
                let trimmed = line.trim();
                if !trimmed.is_empty() {
                    self.line(trimmed);
                }
            }
        }

        // ---- the writer function
        let fn_generics = generics.fn_decl();
        let vis = vis_prefix(&c.vis);
        self.line("#[inline]");

        // Built from parts so each parameter type keeps its link back to the
        // template, which is what lets hovering a type reach `rust-analyzer`.
        let mut signature = vec![Part::owned(format!(
            "{vis}fn {prim}{fn_generics}(__w: &mut {rt}::Writer<'_>",
            rt = self.rt
        ))];
        for param in &params {
            let binding = if param.mutable { "mut " } else { "" };
            signature.push(Part::owned(format!(", {binding}{}: ", param.name)));
            match param.ty_span {
                Some(span) => signature.push(Part::mapped(param.fn_ty.clone(), span)),
                None => signature.push(Part::owned(param.fn_ty.clone())),
            }
        }
        signature.push(Part::owned(format!(
            ") -> {rt}::Result{where_clause} {{",
            rt = self.rt
        )));
        self.open_parts(&signature);
        self.nodes(&c.body)?;
        self.flush_statics();
        self.line("Ok(())");
        self.close("}");
        self.blank();

        // ---- the parameter struct
        let struct_generics = generics.decl();
        let struct_use = generics.usage();
        self.line("#[allow(non_camel_case_types)]");
        if params.is_empty() {
            self.line(&format!(
                "{vis}struct {name}{struct_generics}{where_clause} {{}}",
                name = c.name
            ));
        } else {
            self.open(&format!(
                "{vis}struct {name}{struct_generics}{where_clause} {{",
                name = c.name
            ));
            for param in &params {
                self.line(&format!("pub {}: {},", param.name, param.struct_ty));
            }
            self.close("}");
        }
        self.blank();

        // ---- Template impl
        self.open(&format!(
            "impl{struct_generics} {rt}::Template for {name}{struct_use}{where_clause} {{",
            rt = self.rt,
            name = c.name,
        ));
        self.line("#[inline]");
        self.open(&format!(
            "fn render(self, __w: &mut {rt}::Writer<'_>) -> {rt}::Result {{",
            rt = self.rt
        ));
        let args = params
            .iter()
            .map(|p| format!(", self.{}", p.name))
            .collect::<String>();
        self.line(&format!("{prim}(__w{args})"));
        self.close("}");
        self.close("}");
        self.blank();

        // ---- the constructor
        let ctor_params = params
            .iter()
            .map(|p| format!("{}: {}", p.name, p.struct_ty))
            .collect::<Vec<_>>()
            .join(", ");
        let field_init = params
            .iter()
            .map(|p| p.name.clone())
            .collect::<Vec<_>>()
            .join(", ");
        self.line("#[allow(non_snake_case)]");
        // The constructor is a convenience alternative to the struct literal,
        // so a component that only ever gets built one way should not warn.
        self.line("#[allow(dead_code)]");
        self.line("#[inline]");
        self.open(&format!(
            "{vis}fn {name}{struct_generics}({ctor_params}) -> {name}{struct_use}{where_clause} {{",
            name = c.name
        ));
        if params.is_empty() {
            self.line(&format!("{} {{}}", c.name));
        } else {
            self.line(&format!("{} {{ {field_init} }}", c.name));
        }
        self.close("}");

        self.children_params.clear();
        Ok(())
    }

    /// Works out each parameter's generated types, synthesising lifetimes for
    /// the struct where the source elided them.
    fn resolve_params(&self, c: &Component) -> Result<(Vec<ResolvedParam>, Vec<String>)> {
        let mut resolved = Vec::new();
        let mut synth = Vec::new();
        let mut children_index = 0usize;

        for param in &c.params {
            if param.is_children() {
                let ty = format!("__RsxChildren{children_index}");
                children_index += 1;
                resolved.push(ResolvedParam {
                    name: param.name.clone(),
                    mutable: param.mutable,
                    ty_span: None,
                    fn_ty: ty.clone(),
                    struct_ty: ty,
                    is_children: true,
                });
                continue;
            }

            let struct_ty = name_elided_lifetimes(&param.ty, &mut synth);
            resolved.push(ResolvedParam {
                name: param.name.clone(),
                mutable: param.mutable,
                ty_span: Some(param.ty_span),
                fn_ty: param.ty.clone(),
                struct_ty,
                is_children: false,
            });
        }

        Ok((resolved, synth))
    }

    // --------------------------------------------------------------- nodes

    fn nodes(&mut self, nodes: &[Node]) -> Result<()> {
        for node in nodes {
            self.node(node)?;
        }
        Ok(())
    }

    fn node(&mut self, node: &Node) -> Result<()> {
        let pos = node.span().from;
        self.at(pos, |gen| gen.node_inner(node))
    }

    fn node_inner(&mut self, node: &Node) -> Result<()> {
        match node {
            Node::Text(t) => {
                self.push_static(&escape_static_text(&t.value));
                Ok(())
            }
            Node::Doctype(t) => {
                self.push_static(&t.value);
                Ok(())
            }
            Node::Comment(t) => {
                self.push_static(&format!("<!--{}-->", t.value));
                Ok(())
            }
            Node::Element(e) => self.element(e),
            Node::Fragment(f) => self.nodes(&f.children),
            Node::Call(c) => self.call(c),
            Node::Expr(e) => {
                self.flush_statics();
                if self.children_params.contains(&e.source.text) {
                    let rt = self.rt.clone();
                    self.line_parts(&[
                        Part::owned(format!("{rt}::Template::render(")),
                        Part::frag(&e.source),
                        Part::lit(", __w)?;"),
                    ]);
                } else {
                    // Borrowed, not moved: `{row.name}` must work when `name`
                    // is a `String` reached through a shared reference, and
                    // `&T` is `Display` whenever `T` is. The parentheses keep
                    // the borrow applying to the whole expression.
                    self.line_parts(&[
                        Part::lit("__w.text(&("),
                        Part::frag(&e.source),
                        Part::lit("))?;"),
                    ]);
                }
                Ok(())
            }
            Node::RawExpr(e) => {
                self.flush_statics();
                self.line_parts(&[
                    Part::lit("__w.raw_text(&("),
                    Part::frag(&e.source),
                    Part::lit("))?;"),
                ]);
                Ok(())
            }
            Node::If(n) => self.if_node(n),
            Node::For(n) => {
                self.flush_statics();
                self.open_parts(&[Part::lit("for "), Part::frag(&n.header), Part::lit(" {")]);
                self.nodes(&n.body)?;
                self.flush_statics();
                self.close("}");
                Ok(())
            }
            Node::While(n) => {
                self.flush_statics();
                if n.header == "loop" || n.header == "unsafe" {
                    self.open(&format!("{} {{", n.header));
                } else {
                    self.open_parts(&[Part::lit("while "), Part::frag(&n.header), Part::lit(" {")]);
                }
                self.nodes(&n.body)?;
                self.flush_statics();
                self.close("}");
                Ok(())
            }
            Node::Match(n) => {
                self.flush_statics();
                self.open_parts(&[Part::lit("match "), Part::frag(&n.subject), Part::lit(" {")]);
                for arm in &n.arms {
                    self.open_parts(&[Part::frag(&arm.pattern), Part::lit(" => {")]);
                    self.nodes(&arm.body)?;
                    self.flush_statics();
                    self.close("}");
                }
                self.close("}");
                Ok(())
            }
            Node::Stmt(s) => {
                self.flush_statics();
                self.line_parts(&[Part::frag(&s.source)]);
                Ok(())
            }
        }
    }

    fn if_node(&mut self, n: &If) -> Result<()> {
        self.flush_statics();
        self.open_parts(&[Part::lit("if "), Part::frag(&n.cond), Part::lit(" {")]);
        self.nodes(&n.then_body)?;
        self.flush_statics();
        for branch in &n.else_ifs {
            self.depth = self.depth.saturating_sub(1);
            self.line_parts(&[
                Part::lit("} else if "),
                Part::frag(&branch.cond),
                Part::lit(" {"),
            ]);
            self.depth += 1;
            self.nodes(&branch.body)?;
            self.flush_statics();
        }
        match &n.else_body {
            Some(body) => {
                self.close("} else {");
                self.depth += 1;
                self.nodes(body)?;
                self.flush_statics();
                self.close("}");
            }
            None => self.close("}"),
        }
        Ok(())
    }

    fn element(&mut self, e: &Element) -> Result<()> {
        self.push_static(&format!("<{}", e.tag));

        for attr in &e.attrs {
            match attr {
                Attribute::Static { name, value, .. } => {
                    self.push_static(&format!(" {name}=\"{}\"", escape_static_attr(value)));
                }
                Attribute::Bare { name, .. } => {
                    self.push_static(&format!(" {name}"));
                }
                Attribute::Expr { name, expr, .. } => {
                    self.push_static(&format!(" {name}=\""));
                    self.flush_statics();
                    self.line_parts(&[
                        Part::lit("__w.attr(&("),
                        Part::frag(expr),
                        Part::lit("))?;"),
                    ]);
                    self.push_static("\"");
                }
                Attribute::Conditional { name, expr, .. } => {
                    self.flush_statics();
                    self.line_parts(&[
                        Part::owned(format!("__w.bool_attr({}, ", rust_string_literal(name))),
                        Part::frag(expr),
                        Part::lit(")?;"),
                    ]);
                }
                Attribute::Spread { expr, .. } => {
                    self.flush_statics();
                    self.line_parts(&[
                        Part::lit("__w.spread("),
                        Part::frag(expr),
                        Part::lit(")?;"),
                    ]);
                }
            }
        }

        self.push_static(">");

        if e.void {
            return Ok(());
        }

        if e.raw_text {
            // Character data: a browser does not resolve references inside
            // `<script>` or `<style>`, so escaping `&` or `<` here would
            // corrupt the very JavaScript and CSS it is meant to protect.
            for child in &e.children {
                match child {
                    Node::Text(t) => self.push_static(&t.value),
                    other => self.node(other)?,
                }
            }
        } else {
            self.nodes(&e.children)?;
        }

        self.push_static(&format!("</{}>", e.tag));
        Ok(())
    }

    fn call(&mut self, call: &Call) -> Result<()> {
        self.flush_statics();
        const CHILDREN_LOCAL: &str = "__rsx_children";

        let signature = self.scope.get(call.name());
        // Each field is its own run of parts so the expression inside keeps
        // its link back to the template.
        let mut fields: Vec<Vec<Part<'_>>> = Vec::new();
        let mut spread: Option<&ast::Rust> = None;
        let mut provided: BTreeSet<String> = BTreeSet::new();

        for attr in &call.attrs {
            match attr {
                Attribute::Spread { expr, .. } => {
                    if spread.is_some() {
                        return Err(Error::new(
                            format!("`<{}>` has more than one spread", call.path),
                            attr.span(),
                        ));
                    }
                    spread = Some(expr);
                }
                _ => {
                    let name = attr.name().unwrap_or_default();
                    if !is_rust_ident(name) {
                        return Err(Error::new(
                            format!("`{name}` is not a valid parameter name for `<{}>`", call.path),
                            attr.span(),
                        )
                        .with_help(
                            "component props are struct fields, so they have to be Rust identifiers",
                        ));
                    }
                    if let Some(sig) = signature {
                        if !sig.has_param(name) {
                            return Err(Error::new(
                                format!("component `{}` has no parameter `{name}`", call.path),
                                attr.span(),
                            )
                            .with_help(sig.describe_params()));
                        }
                    }
                    if !provided.insert(name.to_string()) {
                        return Err(Error::new(
                            format!("parameter `{name}` is set twice on `<{}>`", call.path),
                            attr.span(),
                        ));
                    }
                    let mut field = vec![Part::owned(format!("{name}: "))];
                    match attr {
                        Attribute::Static { value, .. } => {
                            field.push(Part::owned(rust_string_literal(value)))
                        }
                        Attribute::Expr { expr, .. } | Attribute::Conditional { expr, .. } => {
                            field.push(Part::frag(expr))
                        }
                        Attribute::Bare { .. } => field.push(Part::lit("true")),
                        Attribute::Spread { .. } => unreachable!(),
                    }
                    fields.push(field);
                }
            }
        }

        // The children block fills the component's markup parameter.
        let children_target = signature.and_then(|sig| sig.children_param(&provided));
        let has_children = !call.children.is_empty();
        if has_children {
            let field = match children_target {
                Some(name) => name.to_string(),
                None if signature.is_some() => {
                    return Err(Error::new(
                        format!("component `{}` does not accept children", call.path),
                        call.span,
                    )
                    .with_help(format!(
                        "give `{}` a parameter of type `Element` to receive them, as in \
                         `fn {}(children: Element) -> Element`",
                        call.path,
                        call.name()
                    )));
                }
                // Unknown component: assume the conventional name and let
                // `rustc` report it if the component disagrees.
                None => "children".to_string(),
            };
            provided.insert(field.clone());
            fields.push(vec![Part::owned(format!("{field}: {CHILDREN_LOCAL}"))]);
        } else if spread.is_none() {
            // A known component with an unfilled markup parameter renders
            // nothing there, which `()` expresses.
            if let Some(sig) = signature {
                for name in sig.unfilled_children(&provided) {
                    fields.push(vec![Part::owned(format!("{name}: ()"))]);
                }
            }
        }

        if let Some(expr) = spread {
            fields.push(vec![Part::lit(".."), Part::frag(expr)]);
        }

        let rt = self.rt.clone();
        let mut line: Vec<Part<'_>> = Vec::new();
        if fields.is_empty() {
            line.push(Part::owned(format!(
                "{rt}::Template::render({} {{}}, __w)?;",
                call.path
            )));
        } else {
            line.push(Part::owned(format!(
                "{rt}::Template::render({} {{ ",
                call.path
            )));
            for (index, field) in fields.into_iter().enumerate() {
                if index > 0 {
                    line.push(Part::lit(", "));
                }
                line.extend(field);
            }
            line.push(Part::lit(" }, __w)?;"));
        }

        // The children closure becomes a local so the generated code stays
        // readable. The extra block scopes that local, so nesting a component
        // call inside another one's children does not collide.
        if has_children {
            self.open("{");
            self.open(&format!("let {CHILDREN_LOCAL} = {rt}::from_fn(|__w| {{"));
            self.nodes(&call.children)?;
            self.flush_statics();
            self.line("Ok(())");
            self.close("});");
            self.line_parts(&line);
            self.close("}");
        } else {
            self.line_parts(&line);
        }
        Ok(())
    }
}

// --------------------------------------------------------------- generics

/// The generic parameter lists the generated items need.
///
/// The writer function and the struct do not want the same list. A function
/// parameter may elide a lifetime, so `fn card(title: &str)` needs no lifetime
/// parameter at all; a struct field may not, so `struct Card<'a>` does. The
/// synthesised lifetimes therefore appear on the struct, its impl and its
/// constructor, but not on the writer function.
struct Generics {
    user_lifetimes: Vec<String>,
    synth_lifetimes: Vec<String>,
    user_types: Vec<String>,
    children_types: Vec<String>,
}

impl Generics {
    fn build(
        user: &str,
        synth_lifetimes: &[String],
        params: &[ResolvedParam],
        runtime: &str,
    ) -> Generics {
        let mut user_lifetimes = Vec::new();
        let mut user_types = Vec::new();

        for entry in split_top_level(user, ',') {
            let entry = entry.trim();
            if entry.is_empty() {
                continue;
            }
            if entry.starts_with('\'') {
                user_lifetimes.push(entry.to_string());
            } else {
                user_types.push(entry.to_string());
            }
        }

        let children_types = params
            .iter()
            .filter(|p| p.is_children)
            .map(|p| format!("{}: {runtime}::Template", p.struct_ty))
            .collect();

        Generics {
            user_lifetimes,
            synth_lifetimes: synth_lifetimes.to_vec(),
            user_types,
            children_types,
        }
    }

    /// `<'a, T: Display>` for the struct, its impl and its constructor.
    ///
    /// Rust requires lifetimes before type parameters, so the four groups are
    /// concatenated in that order rather than in declaration order.
    fn decl(&self) -> String {
        let mut all = self.user_lifetimes.clone();
        all.extend(self.synth_lifetimes.iter().cloned());
        all.extend(self.user_types.iter().cloned());
        all.extend(self.children_types.iter().cloned());
        wrap_angles(&all)
    }

    /// The same list without the lifetimes the struct alone needs.
    fn fn_decl(&self) -> String {
        let mut all = self.user_lifetimes.clone();
        all.extend(self.user_types.iter().cloned());
        all.extend(self.children_types.iter().cloned());
        wrap_angles(&all)
    }

    /// `<'a, T>` for naming the struct type.
    fn usage(&self) -> String {
        let mut names: Vec<String> = self
            .user_lifetimes
            .iter()
            .map(|e| generic_name(e))
            .collect();
        names.extend(self.synth_lifetimes.iter().cloned());
        names.extend(self.user_types.iter().map(|e| generic_name(e)));
        names.extend(self.children_types.iter().map(|e| generic_name(e)));
        wrap_angles(&names)
    }
}

fn wrap_angles(parts: &[String]) -> String {
    if parts.is_empty() {
        String::new()
    } else {
        format!("<{}>", parts.join(", "))
    }
}

/// Extracts the name a generic parameter declares.
fn generic_name(entry: &str) -> String {
    let entry = entry.trim();
    if let Some(rest) = entry.strip_prefix("const ") {
        return rest.split(':').next().unwrap_or("").trim().to_string();
    }
    let end = entry
        .find(|c: char| c == ':' || c == '=' || c.is_whitespace())
        .unwrap_or(entry.len());
    entry[..end].trim().to_string()
}

/// Splits on `sep` at nesting depth zero.
fn split_top_level(s: &str, sep: char) -> Vec<String> {
    let mut parts = Vec::new();
    let mut depth = 0i32;
    let mut current = String::new();
    for ch in s.chars() {
        match ch {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth -= 1,
            _ => {}
        }
        if ch == sep && depth == 0 {
            parts.push(std::mem::take(&mut current));
        } else {
            current.push(ch);
        }
    }
    if !current.trim().is_empty() {
        parts.push(current);
    }
    parts
}

/// Gives every elided reference in `ty` a named lifetime.
///
/// A struct field cannot elide a lifetime the way a function parameter can, so
/// `&str` becomes `&'__rsx0 str` and the new name is recorded for the generic
/// parameter list.
fn name_elided_lifetimes(ty: &str, synth: &mut Vec<String>) -> String {
    let bytes = ty.as_bytes();
    let mut out = String::with_capacity(ty.len() + 8);
    let mut i = 0usize;

    while i < bytes.len() {
        if bytes[i] != b'&' {
            let ch_len = utf8_len(bytes[i]);
            out.push_str(&ty[i..i + ch_len]);
            i += ch_len;
            continue;
        }

        out.push('&');
        i += 1;

        // `&&str` is two references; each needs its own lifetime, so the inner
        // one is handled by the next pass of the loop.
        let mut j = i;
        while j < bytes.len() && bytes[j].is_ascii_whitespace() {
            j += 1;
        }
        if j < bytes.len() && bytes[j] == b'\'' {
            // Already named; copy the whitespace through and move on.
            out.push_str(&ty[i..j]);
            i = j;
            continue;
        }

        let name = format!("{SYNTH_LIFETIME_PREFIX}{}", synth.len());
        synth.push(name.clone());
        out.push_str(&name);
        out.push(' ');
        i = j;
    }

    out
}

fn utf8_len(b: u8) -> usize {
    match b {
        0x00..=0x7F => 1,
        0xC0..=0xDF => 2,
        0xE0..=0xEF => 3,
        _ => 4,
    }
}

// ----------------------------------------------------------------- helpers

fn vis_prefix(vis: &str) -> String {
    if vis.is_empty() {
        String::new()
    } else {
        format!("{vis} ")
    }
}

fn is_rust_ident(s: &str) -> bool {
    !s.is_empty()
        && s.chars()
            .next()
            .is_some_and(|c| c.is_alphabetic() || c == '_')
        && s.chars().all(|c| c.is_alphanumeric() || c == '_')
}

/// Renders `s` as a Rust string literal.
fn rust_string_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Escapes static text written in a template.
///
/// Templates are written as HTML, so an author who types `&amp;` or `&nbsp;`
/// means the character reference, not a literal ampersand — escaping it again
/// would render `&amp;amp;`. A bare `&`, as in `AT&T`, does get escaped.
fn escape_static_text(s: &str) -> String {
    escape_static(s, false)
}

/// The same rule for a literal attribute value, which also has to escape the
/// quote characters that would end it.
fn escape_static_attr(s: &str) -> String {
    escape_static(s, true)
}

fn escape_static(s: &str, attribute: bool) -> String {
    let bytes = s.as_bytes();
    let mut out = String::with_capacity(s.len());
    let mut i = 0usize;

    while i < bytes.len() {
        match bytes[i] {
            b'&' => {
                if character_reference_len(&bytes[i..]).is_some() {
                    out.push('&');
                } else {
                    out.push_str("&amp;");
                }
                i += 1;
            }
            b'<' => {
                out.push_str("&lt;");
                i += 1;
            }
            b'>' => {
                out.push_str("&gt;");
                i += 1;
            }
            b'"' if attribute => {
                out.push_str("&#34;");
                i += 1;
            }
            b'\'' if attribute => {
                out.push_str("&#39;");
                i += 1;
            }
            b => {
                let len = utf8_len(b);
                out.push_str(&s[i..i + len]);
                i += len;
            }
        }
    }

    out
}

/// Length of the character reference starting at `bytes`, if there is one.
///
/// Accepts the three HTML forms: `&name;`, `&#1234;` and `&#x1F600;`. The
/// bounds match what a browser will accept, so an `&` followed by a long run
/// of letters and a semicolon is still treated as a literal ampersand.
fn character_reference_len(bytes: &[u8]) -> Option<usize> {
    debug_assert_eq!(bytes.first(), Some(&b'&'));
    let rest = bytes.get(1..)?;

    let (digits, radix_offset): (&[u8], usize) = match rest.first()? {
        b'#' => match rest.get(1) {
            Some(b'x') | Some(b'X') => (rest.get(2..)?, 2),
            _ => (rest.get(1..)?, 1),
        },
        _ => {
            // A named reference: a letter, then letters and digits.
            if !rest[0].is_ascii_alphabetic() {
                return None;
            }
            let len = rest
                .iter()
                .take_while(|b| b.is_ascii_alphanumeric())
                .count();
            // Between 2 and 32 characters, then a semicolon.
            if (2..=32).contains(&len) && rest.get(len) == Some(&b';') {
                return Some(1 + len + 1);
            }
            return None;
        }
    };

    let hex = radix_offset == 2;
    let len = digits
        .iter()
        .take_while(|b| {
            if hex {
                b.is_ascii_hexdigit()
            } else {
                b.is_ascii_digit()
            }
        })
        .count();
    let max = if hex { 6 } else { 7 };
    if (1..=max).contains(&len) && digits.get(len) == Some(&b';') {
        Some(1 + radix_offset + len + 1)
    } else {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_elided_lifetimes() {
        let mut synth = Vec::new();
        assert_eq!(name_elided_lifetimes("&str", &mut synth), "&'__rsx_a0 str");
        assert_eq!(synth, vec!["'__rsx_a0".to_string()]);
    }

    #[test]
    fn keeps_named_lifetimes() {
        let mut synth = Vec::new();
        assert_eq!(name_elided_lifetimes("&'a str", &mut synth), "&'a str");
        assert!(synth.is_empty());
    }

    #[test]
    fn names_nested_references() {
        let mut synth = Vec::new();
        let out = name_elided_lifetimes("&[&str]", &mut synth);
        assert_eq!(out, "&'__rsx_a0 [&'__rsx_a1 str]");
        assert_eq!(synth.len(), 2);
    }

    #[test]
    fn splits_generic_lists_at_depth_zero() {
        let parts = split_top_level("'a, T: Into<Vec<u8>>, U", ',');
        assert_eq!(parts.len(), 3);
        assert_eq!(parts[1].trim(), "T: Into<Vec<u8>>");
    }

    #[test]
    fn extracts_generic_names() {
        assert_eq!(generic_name("'a"), "'a");
        assert_eq!(generic_name("T: Display"), "T");
        assert_eq!(generic_name("const N: usize"), "N");
    }

    #[test]
    fn escapes_bare_ampersands_but_not_references() {
        assert_eq!(escape_static_text("AT&T"), "AT&amp;T");
        assert_eq!(escape_static_text("Tom &amp; Jerry"), "Tom &amp; Jerry");
        assert_eq!(escape_static_text("1&nbsp;000"), "1&nbsp;000");
        assert_eq!(escape_static_text("&#8212; &#x2014;"), "&#8212; &#x2014;");
        assert_eq!(escape_static_text("R&D and more"), "R&amp;D and more");
        assert_eq!(escape_static_text("a &lt; b"), "a &lt; b");
    }

    #[test]
    fn escapes_angle_brackets_in_static_text() {
        assert_eq!(escape_static_text("a < b > c"), "a &lt; b &gt; c");
    }

    #[test]
    fn escapes_quotes_only_in_attributes() {
        assert_eq!(escape_static_text("say \"hi\""), "say \"hi\"");
        assert_eq!(escape_static_attr("say \"hi\""), "say &#34;hi&#34;");
        assert_eq!(escape_static_attr("it's"), "it&#39;s");
    }

    #[test]
    fn rejects_malformed_character_references() {
        // No semicolon, too long, or empty: all literal ampersands.
        assert_eq!(escape_static_text("&amp"), "&amp;amp");
        assert_eq!(escape_static_text("&a;"), "&amp;a;");
        assert_eq!(escape_static_text("&#;"), "&amp;#;");
        assert_eq!(escape_static_text("&#12345678;"), "&amp;#12345678;");
        assert_eq!(escape_static_text("& "), "&amp; ");
    }

    #[test]
    fn escapes_string_literals() {
        assert_eq!(rust_string_literal("a\"b\\c"), "\"a\\\"b\\\\c\"");
    }
}
